#ifndef DRV_ADC_H
#define DRV_ADC_H

#include <stdint.h>

/*
 * ADC采样驱动：ADC1单通道软件触发采样+均值滤波。
 * 用于烟雾传感器等模拟量采集，引脚/通道参数在drv_adc.c顶部宏配置
 * (默认PA0/ADC1_IN0，改接线时同步改宏)。
 */

/*******************************************************************
** 函数名	: drv_adc_init
** 函数描述	: ADC1初始化：GPIO模拟输入+ADC配置(12bit软件触发)
** 参数		: 无
** 返回		: 无
********************************************************************/
void drv_adc_init(void);

/*******************************************************************
** 函数名	: drv_adc_read
** 函数描述	: 单通道连续N次采样取均值(滤波)，返回原始ADC值
** 参数		: 无
** 返回		: 采样值(12bit 0~4095)
********************************************************************/
uint16_t drv_adc_read(void);

/*******************************************************************
** 函数名	: drv_adc_read_mv
** 函数描述	: 采样并换算电压值
** 参数		: 无
** 返回		: 电压(mV), 3.3V参考
********************************************************************/
uint16_t drv_adc_read_mv(void);

#endif /* DRV_ADC_H */
