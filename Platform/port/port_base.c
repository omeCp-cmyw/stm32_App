#include "stm32f4xx.h"
#include "port_base.h"

/*
 * STM32F407平台移植实现：
 * 换芯片时仅需重写本文件，接口定义见port_base.h
 */

/*******************************************************************
** 函数名	: port_enter_critical
** 函数描述	: 进入临界区（关全局中断）
** 参数		: 无
** 返回		: 无
********************************************************************/
void port_enter_critical(void)
{
    __disable_irq();
}

/*******************************************************************
** 函数名	: port_exit_critical
** 函数描述	: 退出临界区（恢复全局中断）
** 参数		: 无
** 返回		: 无
********************************************************************/
void port_exit_critical(void)
{
    __enable_irq();
}

/*******************************************************************
** 函数名	: port_system_reset
** 函数描述	: 系统复位：复位前直接写IWDG密钥寄存器喂一次狗，
**			避免看门狗先于NVIC复位触发，保证复位标志清晰
** 参数		: 无
** 返回		: 无
********************************************************************/
void port_system_reset(void)
{
    __disable_irq();

    IWDG->KR = 0xAAAA;          /* 喂狗（IWDG未启动时写入无害） */
    NVIC_SystemReset();

    for (;;) {
        ;                       /* 复位前死等 */
    }
}
