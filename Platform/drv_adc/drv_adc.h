#ifndef __DRV_ADC_H
#define __DRV_ADC_H

#include <stdint.h>

/* ADC通道定义 */
typedef enum {
    ADC_CH_LIGHT = 0,   /* 光照传感器（PA1/ADC1_IN1） */
    ADC_CH_MQ2,         /* MQ2气体传感器（PA0/ADC1_IN0, 与参考工程一致） */
    ADC_CH_MAX
} adc_ch_t;

/*******************************************************************************
** 函数名称    drv_adc_init
** 函数说明    初始化ADC1两通道（GPIO模拟输入+12bit软件触发配置）
** 输入参数    无
** 输出参数    无
** 返回参数    无
*******************************************************************************/
void drv_adc_init(void);

/*******************************************************************************
** 函数名称    drv_adc_read
** 函数说明    指定通道连续N次采样取均值（滤波），返回原始ADC值
** 输入参数    ch: ADC通道
** 输出参数    无
** 返回参数    采样值（12bit 0~4095），通道非法返回0
*******************************************************************************/
uint16_t drv_adc_read(adc_ch_t ch);

/*******************************************************************************
** 函数名称    drv_adc_read_mv
** 函数说明    指定通道采样并换算电压值
** 输入参数    ch: ADC通道
** 输出参数    无
** 返回参数    电压（mV），3.3V参考，通道非法返回0
*******************************************************************************/
uint16_t drv_adc_read_mv(adc_ch_t ch);

#endif /* __DRV_ADC_H */
