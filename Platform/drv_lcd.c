#include "drv_lcd.h"
#include "drv_lcd/bsp_nt35510_lcd.h"
#include <stdio.h>

/*******************************************************************************
** 函数名称    drv_lcd_init
** 函数说明    初始化LCD驱动
** 输入参数    无
** 输出参数    无
** 返回参数    0: 成功
*******************************************************************************/
int drv_lcd_init(void)
{
    /* 初始化NT35510：GPIO + FMC + 寄存器序列 + 清屏 + 背光 */
    NT35510_Init();

    /* 默认字体16x32，白字黑底 */
    LCD_SetFont(&Font16x32);
    LCD_SetColors(WHITE, BLACK);

    printf("[DRV_LCD] LCD driver initialized (%dx%d)\r\n", LCD_X_LENGTH, LCD_Y_LENGTH);
    return 0;
}

/*******************************************************************************
** 函数名称    drv_lcd_deinit
** 函数说明    反初始化LCD驱动
** 输入参数    无
** 输出参数    无
** 返回参数    0: 成功
*******************************************************************************/
int drv_lcd_deinit(void)
{
    /* 关闭背光 */
    NT35510_BackLed_Control(DISABLE);

    printf("[DRV_LCD] LCD driver deinitialized\r\n");
    return 0;
}

/*******************************************************************************
** 函数名称    drv_lcd_clear
** 函数说明    清屏
** 输入参数    color: 颜色值(RGB565)
** 输出参数    无
** 返回参数    0: 成功
*******************************************************************************/
int drv_lcd_clear(uint32_t color)
{
    LCD_SetBackColor((uint16_t)color);
    NT35510_Clear(0, 0, LCD_X_LENGTH, LCD_Y_LENGTH);
    return 0;
}

/*******************************************************************************
** 函数名称    drv_lcd_fill_rect
** 函数说明    填充矩形区域
** 输入参数    region: 区域指针
** 输出参数    无
** 返回参数    0: 成功
*******************************************************************************/
int drv_lcd_fill_rect(LCD_Region_t *region, uint32_t color)
{
    if (region == NULL) {
        return -1;
    }

    /* 借用文字颜色填充实心矩形 */
    LCD_SetTextColor((uint16_t)color);
    NT35510_DrawRectangle(region->x, region->y, region->width, region->height, 1);
    return 0;
}

/*******************************************************************************
** 函数名称    drv_lcd_draw_pixel
** 函数说明    画点
** 输入参数    x: X坐标
** 输出参数    无
** 返回参数    0: 成功
*******************************************************************************/
int drv_lcd_draw_pixel(uint16_t x, uint16_t y, uint32_t color)
{
    LCD_SetTextColor((uint16_t)color);
    NT35510_SetPointPixel(x, y);
    return 0;
}

/*******************************************************************************
** 函数名称    drv_lcd_draw_string
** 函数说明    显示字符串(仅英文)
** 输入参数    x: X坐标
** 输出参数    无
** 返回参数    0: 成功
*******************************************************************************/
int drv_lcd_draw_string(uint16_t x, uint16_t y, const char *str, uint32_t color)
{
    if (str == NULL) {
        return -1;
    }

    LCD_SetTextColor((uint16_t)color);
    NT35510_DispString_EN(x, y, (char *)str);
    return 0;
}

/*******************************************************************************
** 函数名称    drv_lcd_set_backlight
** 函数说明    设置背光亮度
** 输入参数    brightness: 亮度(0-100)，0关闭，其他开启
** 输出参数    无
** 返回参数    0: 成功
*******************************************************************************/
int drv_lcd_set_backlight(uint8_t brightness)
{
    if (brightness > 0) {
        NT35510_BackLed_Control(ENABLE);
    } else {
        NT35510_BackLed_Control(DISABLE);
    }
    return 0;
}

/*******************************************************************************
** 函数名称    drv_lcd_get_width
** 函数说明    获取LCD宽度
** 输入参数    无
** 输出参数    无
** 返回参数    LCD宽度
*******************************************************************************/
int drv_lcd_get_width(void)
{
    return LCD_X_LENGTH;
}

/*******************************************************************************
** 函数名称    drv_lcd_get_height
** 函数说明    获取LCD高度
** 输入参数    无
** 输出参数    无
** 返回参数    LCD高度
*******************************************************************************/
int drv_lcd_get_height(void)
{
    return LCD_Y_LENGTH;
}
