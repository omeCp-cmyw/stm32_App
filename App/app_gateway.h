#ifndef APP_GATEWAY_H
#define APP_GATEWAY_H

/*
 * 网关业务编排层：App层唯一业务入口。
 * 初始化顺序编排(物模型->传感器->云端)与主循环业务调度
 * (传感器采集轮询/状态指示/越限告警上报)。
 * 更换云平台或新增传感器只需改本模块注册处, 其余分层不动。
 */

/*******************************************************************
** 函数名	: app_gateway_init
** 函数描述	: 业务总初始化：物模型绑定->传感器注册->云平台接入
** 参数		: 无
** 返回		: 无
********************************************************************/
void app_gateway_init(void);

/*******************************************************************
** 函数名	: app_gateway_loop
** 函数描述	: 业务主循环：传感器采集轮询/状态LED/告警事件上报
** 参数		: 无
** 返回		: 无
********************************************************************/
void app_gateway_loop(void);

#endif /* APP_GATEWAY_H */
