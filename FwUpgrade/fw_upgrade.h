#ifndef FW_UPGRADE_H
#define FW_UPGRADE_H

#include "osal_types.h"

/*
********************************************************************************
* 固件升级主控：
* 传输通道把固件数据流经 FW_UPG_WriteData 写入APP备份分区，
* 下载完成后 FW_UPG_Finish 校验并在Sector4写升级标志，复位交Bootloader搬运。
********************************************************************************
*/

/* 升级状态 */
typedef enum {
    FW_UPG_STATE_IDLE = 0,      /* 空闲，等待升级数据 */
    FW_UPG_STATE_RECVING,       /* 正在接收固件数据 */
    FW_UPG_STATE_MAX
} FW_UPG_STATE_E;

/* 升级结果 */
typedef enum {
    FW_UPG_RESULT_NULL = 0,
    FW_UPG_RESULT_SUCCESS,      /* 固件升级成功 */
    FW_UPG_RESULT_CHKERR,       /* 固件校验失败 */
    FW_UPG_RESULT_VERERR,       /* 固件非法：大小越界、报文头错误 */
    FW_UPG_RESULT_OTHER,        /* 其他：取消、读取出错等 */
    FW_UPG_RESULT_MAX
} FW_UPG_RESULT_E;

#define FW_UPG_FLAG_MAGIC       0x50555746     /* 升级标志魔数，ASCII"FWUP" */
#define FW_UPG_FLAG_ADDR        0x08010000     /* 升级标志区，Sector4起始 */

/*******************************************************************
** 函数名	: FW_UPG_Init
** 函数描述	: 升级主控初始化，复位状态机。
** 参数		: 无
** 返回		: 无
********************************************************************/
void FW_UPG_Init(void);

/*******************************************************************
** 函数名	: FW_UPG_SetBkupFlag
** 函数描述	: 写升级标志到备份寄存器BKP0R，跨复位/掉电保持，
**			: 内部完成PWR时钟使能与备份域解锁。
** 参数		: [in] flag: 标志值，传0清除标志
** 返回		: 无
********************************************************************/
void FW_UPG_SetBkupFlag(INT32U flag);

/*******************************************************************
** 函数名	: FW_UPG_StartUpdate
** 函数描述	: 启动固件升级，擦除APP备份分区（Sector8~10）。
** 参数		: [in] fwsize: 固件总字节数
** 返回		: 成功true，失败false
********************************************************************/
BOOLEAN FW_UPG_StartUpdate(INT32U fwsize);

/*******************************************************************
** 函数名	: FW_UPG_StopUpdate
** 函数描述	: 停止固件升级：全部状态标志恢复默认（空闲+清零），
**			: 供传输失败后重开窗口等待下一次新任务。
** 参数		: 无
** 返回		: 无
********************************************************************/
void FW_UPG_StopUpdate(void);

/*******************************************************************
** 函数名	: FW_UPG_WriteData
** 函数描述	: 写入一段固件数据到备份分区，内部处理4字节对齐缓冲。
** 参数		: [in] data: 数据指针
**			: [in] len:  数据字节数
** 返回		: 成功true，失败false
********************************************************************/
BOOLEAN FW_UPG_WriteData(INT8U *data, INT32U len);

/*******************************************************************
** 函数名	: FW_UPG_Finish
** 函数描述	: 固件接收结束：校验大小与CRC32，写升级标志后软复位，
**			: 复位后由Bootloader读标志搬运固件到APP分区。
** 参数		: 无
** 返回		: 升级结果，见FW_UPG_RESULT_E
********************************************************************/
INT8U FW_UPG_Finish(void);

/*******************************************************************
** 函数名	: FW_UPG_GetState
** 函数描述	: 获取当前升级状态。
** 参数		: 无
** 返回		: 升级状态，见FW_UPG_STATE_E
********************************************************************/
INT8U FW_UPG_GetState(void);

/*******************************************************************
** 函数名	: FW_UPG_GetRecvSize
** 函数描述	: 获取已接收的固件字节数。
** 参数		: 无
** 返回		: 已收字节数
********************************************************************/
INT32U FW_UPG_GetRecvSize(void);

/*******************************************************************
** 函数名	: FW_UPG_GetFwSize
** 函数描述	: 获取头报文声明的固件总字节数。
** 参数		: 无
** 返回		: 固件总字节数，未启动升级时为0
********************************************************************/
INT32U FW_UPG_GetFwSize(void);

#endif /* FW_UPGRADE_H */
