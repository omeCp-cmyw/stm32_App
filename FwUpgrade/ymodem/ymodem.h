#ifndef YMODEM_H
#define YMODEM_H

#include <stdint.h>

/*
********************************************************************************
* 串口Ymodem本地升级通道
* 设备为接收方：上电开升级窗口发'C'握手，窗口内无传输则关闭
* 接收侧逐字节组包，由Ymodem任务1ms周期驱动
* 出向控制字符ACK/NAK/CAN阻塞直发，'C'握手带重发
* 解出的固件数据经fw_upgrade主控写入备份分区
* 物理通道：USART3 PB10/PB11
********************************************************************************
*/

/* Ymodem协议字节定义 */
#define YMODEM_SOH              0x01     /* 128字节数据包头 */
#define YMODEM_STX              0x02     /* 1024字节数据包头 */
#define YMODEM_EOT              0x04     /* 传输结束 */
#define YMODEM_ACK              0x06
#define YMODEM_NAK              0x15
#define YMODEM_CAN              0x18
#define YMODEM_CRC_REQ          'C'      /* 接收方握手字符，请求CRC模式 */

/*******************************************************************
** 函数名	: FW_UPG_YM_Init
** 函数描述	: Ymodem通道初始化：复位组包状态机与发送重发句柄，
**			: 随后打开升级窗口（直发首个'C'并挂队列每秒重发）。
** 参数		: 无
** 返回		: 无
********************************************************************/
void FW_UPG_YM_Init(void);

/*******************************************************************
** 函数名	: FW_UPG_YM_Task
** 函数描述	: Ymodem任务入口：1ms周期泵UART3数据驱动组包状态机，
**			: 处理窗口超时/接收超时/发送重发时序。
** 参数		: [in] arg: 任务参数，未使用
** 返回		: 无
********************************************************************/
void FW_UPG_YM_Task(void *arg);

/*******************************************************************
** 函数名	: FW_UPG_YM_IsArmed
** 函数描述	: 查询是否处于升级等待态（含接收中）。
** 参数		: 无
** 返回		: 1升级等待/接收中，0正常态静默
********************************************************************/
uint8_t FW_UPG_YM_IsArmed(void);

/*******************************************************************
** 函数名	: FW_UPG_YM_SendByte
** 函数描述	: 即时直发一个控制字符，不进发送队列。
** 参数		: [in] ch: 控制字符
** 返回		: 无
********************************************************************/
void FW_UPG_YM_SendByte(uint8_t ch);

/*******************************************************************
** 函数名	: FW_UPG_YM_ListSend
** 函数描述	: 挂发送重发句柄：控制字符立即首发一次，随后按周期重发。
** 参数		: [in] type:    控制字符（Ymodem协议字节）
**			: [in] ct_send: 重发次数，0为只发一次
**			: [in] ct_time: 重发等待时长，单位ms
** 返回		: 成功1，失败0
********************************************************************/
uint8_t FW_UPG_YM_ListSend(uint8_t type, uint8_t ct_send, uint16_t ct_time);

/*******************************************************************
** 函数名	: FW_UPG_YM_ListAck
** 函数描述	: 发送重发句柄应答确认：按报文类型查找并摘除。
** 参数		: [in] type: 报文类型（控制字符）
** 返回		: 摘除成功1，未找到0
********************************************************************/
uint8_t FW_UPG_YM_ListAck(uint8_t type);

#endif /* YMODEM_H */
