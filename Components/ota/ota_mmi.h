#ifndef __OTA_MMI_H
#define __OTA_MMI_H

#include <stdint.h>

/* OTA状态机步骤 */
typedef enum {
    OTA_STEP_IDLE = 0,          /* 空闲，等待触发 */
    OTA_STEP_OPEN,              /* 打开TCP连接 */
    OTA_STEP_VERSION,           /* 版本上报 */
    OTA_STEP_CHECK,             /* 升级检查 */
    OTA_STEP_DOWNLOAD,          /* 固件分片下载 */
    OTA_STEP_VERIFY,            /* MD5校验 */
    OTA_STEP_STATUS,            /* 状态上报(100/201) */
    OTA_STEP_FINISH,            /* 完成，复位交Bootloader */
    OTA_STEP_MAX
} ota_step_t;

/*******************************************************************
** 函数名	: ota_task_proc
** 函数描述	: OTA一轮完整流程（同步阻塞）：连接→版本上报→检查
**             →分片下载→MD5校验→状态上报→复位。
**             升级进行中（Ymodem/OTA）则放弃本轮。
** 参数		: 无
** 返回		: 无
********************************************************************/
void ota_task_proc(void);

/*******************************************************************
** 函数名	: ota_get_step
** 函数描述	: 查询当前OTA状态机步骤
** 参数		: 无
** 返回		: ota_step_t步骤
********************************************************************/
ota_step_t ota_get_step(void);

/*******************************************************************
** 函数名	: ota_is_busy
** 函数描述	: 查询OTA是否正在进行（非IDLE）
** 参数		: 无
** 返回		: 1忙, 0空闲
********************************************************************/
uint8_t ota_is_busy(void);

#endif /* __OTA_MMI_H */
