#ifndef __NTP_MMI_H
#define __NTP_MMI_H

#include <stdint.h>

#define NTP_MMI_PACKET_SIZE     48

/*******************************************************************************
** 函数名称    NTP_MMI_BuildRequest
** 函数说明    构建48字节NTP v3客户端请求包
** 输入参数    buf: 输出缓冲(至少48字节)
** 输出参数    无
** 返回参数    无
*******************************************************************************/
void NTP_MMI_BuildRequest(uint8_t *buf);

/*******************************************************************************
** 函数名称    NTP_MMI_ParseReply
** 函数说明    校验并解析NTP应答，提取服务器时间戳
** 输入参数    data: 应答数据
**             len: 数据长度
** 输出参数    unix_ts: Unix时间戳
** 返回参数    0: 合法, -1: 非法
*******************************************************************************/
int32_t NTP_MMI_ParseReply(const uint8_t *data, int32_t len, uint32_t *unix_ts);

/*******************************************************************************
** 函数名称    NTP_MMI_SetTime
** 函数说明    以Unix时间戳建立本地时间基准，并打印UTC/北京时间
** 输入参数    unix_ts: Unix时间戳
** 输出参数    无
** 返回参数    无
*******************************************************************************/
void NTP_MMI_SetTime(uint32_t unix_ts);

/*******************************************************************************
** 函数名称    NTP_MMI_TimeValid
** 函数说明    查询时间是否已同步成功
** 输入参数    无
** 输出参数    无
** 返回参数    1: 有效, 0: 未同步
*******************************************************************************/
uint8_t NTP_MMI_TimeValid(void);

/*******************************************************************************
** 函数名称    NTP_MMI_NowUnix
** 函数说明    由同步基准+单调时钟推算当前Unix时间
** 输入参数    无
** 输出参数    无
** 返回参数    Unix秒, 未同步返回0
*******************************************************************************/
uint32_t NTP_MMI_NowUnix(void);

/*******************************************************************************
** 函数名称    NTP_MMI_NowMs
** 函数说明    当前Unix毫秒时间戳(自同步基准+单调时钟推算)
** 输入参数    无
** 输出参数    无
** 返回参数    毫秒, 未同步返回0
*******************************************************************************/
uint64_t NTP_MMI_NowMs(void);

#endif /* __NTP_MMI_H */
