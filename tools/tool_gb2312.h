#ifndef TOOL_GB2312_H
#define TOOL_GB2312_H

#include "os_type.h"

/*
********************************************************************************
* GB2312到UCS2编码转换（移植自野火yx_gb_to_ucs2）：
* 查表法转换，码表约147KB只读数据，占用Flash ROM，
* 仅在需要中文显示（如TFT屏）时才将该.c编译进工程。
********************************************************************************
*/

/*******************************************************************
** 函数名:     TOOL_GB2312_ToUcs2
** 函数描述:   将缓冲区中的GB2312码转换成UCS2（大端存放，高字节在前）
** 参数:       [out] dptr:   目标缓冲区
**             [in]  sptr:   源缓冲区（GB2312编码）
**             [in]  slen:   源缓冲区字节数
**             [in]  maxlen: 目标缓冲区最大字节数
** 返回:       转换成UCS2后的数据字节长度，失败返回0
********************************************************************/
INT16U TOOL_GB2312_ToUcs2(INT8U *dptr, const INT8U *sptr, INT16U slen, INT16U maxlen);

#endif
