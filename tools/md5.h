#ifndef __MD5_H
#define __MD5_H

#include <stdint.h>

#define MD5_DIGEST_LENGTH 16
#define MD5_CBLOCK        64

typedef struct {
    uint32_t A, B, C, D;            /* 链接变量 */
    uint32_t Nl, Nh;                /* 已处理位长度(低/高32位) */
    uint32_t data[MD5_CBLOCK / 4];  /* 未处理数据块 */
    uint32_t num;                   /* data中有效字节数 */
} MD5_CTX;

/*******************************************************************************
** 函数名称    MD5_Init
** 函数说明    初始化MD5上下文
** 输入参数    c: 上下文
** 输出参数    无
** 返回参数    1: 成功
*******************************************************************************/
int MD5_Init(MD5_CTX *c);

/*******************************************************************************
** 函数名称    MD5_Update
** 函数说明    追加摘要数据
** 输入参数    c: 上下文
**             data: 数据
**             len: 数据长度
** 输出参数    无
** 返回参数    1: 成功
*******************************************************************************/
int MD5_Update(MD5_CTX *c, const void *data, uint32_t len);

/*******************************************************************************
** 函数名称    MD5_Final
** 函数说明    完成摘要计算，输出16字节摘要
** 输入参数    c: 上下文
** 输出参数    md: 摘要缓冲(16字节)
** 返回参数    1: 成功
*******************************************************************************/
int MD5_Final(uint8_t *md, MD5_CTX *c);

/*******************************************************************************
** 函数名称    MD5
** 函数说明    一次性计算数据MD5摘要
** 输入参数    d: 数据
**             n: 数据长度
** 输出参数    md: 摘要缓冲(16字节)，NULL时用内部静态缓冲
** 返回参数    摘要指针
*******************************************************************************/
uint8_t *MD5(const uint8_t *d, uint32_t n, uint8_t *md);

#endif /* __MD5_H */
