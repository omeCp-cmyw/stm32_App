#ifndef TOOL_HEAPMEM_H
#define TOOL_HEAPMEM_H

#include "osal_types.h"

/*
********************************************************************************
* 静态堆内存管理：
* 双向链表内存块+首适配分配，释放时前后向合并碎片；
* 不使用malloc，内存池为编译期静态数组，嵌入式安全。
********************************************************************************
*/

#define SIZE_HEAP_MEM        (4 * 1024)          /* 内存池大小，按需调整 */

/* 分配宏：携带文件名/行号便于调试（接口保留，当前实现不消费） */
#define TOOL_DYM_Alloc(SIZE)             HEAPMEM_Alloc(SIZE, __FILE__, __LINE__)
#define TOOL_DYM_Free(PTR)               HEAPMEM_Free(PTR, __FILE__, __LINE__)

/* 内存池统计信息 */
typedef struct memquery_t {
    INT32U occupysize;                                     /* 已使用的内存大小 */
    INT32U blocks;                                         /* 内存块数量 */
} HEAPMEM_STATISTICS_T;

/*******************************************************************
** 函数名	: TOOL_HEAPMEM_Init
** 函数描述	: 初始化堆内存管理模块，将内存池复位为单个空闲块。
** 参数		: 无
** 返回		: 无
********************************************************************/
void TOOL_HEAPMEM_Init(void);

/*******************************************************************
** 函数名	: HEAPMEM_Alloc
** 函数描述	: 申请分配内存，从空闲块中切出并返回数据区地址。
** 参数		: [in] datalen: 申请内存的长度
**			: [in] file:    申请内存的文件名（调试留痕）
**			: [in] line:    申请内存的行号（调试留痕）
** 返回		: 成功返回内存指针，失败返回0
********************************************************************/
void *HEAPMEM_Alloc(INT32U datalen, char *file, INT32U line);

/*******************************************************************
** 函数名	: HEAPMEM_Free
** 函数描述	: 释放内存，归还块并做前后向合并。
** 参数		: [in] sptr: 释放内存的地址（Alloc返回的指针）
**			: [in] file: 释放内存的文件名（调试留痕）
**			: [in] line: 释放内存的行号（调试留痕）
** 返回		: 无
********************************************************************/
void HEAPMEM_Free(void *sptr, char *file, INT32U line);

/*******************************************************************
** 函数名	: TOOL_HEAPMEM_GetStatistics
** 函数描述	: 查询内存池当前使用状态。
** 参数		: 无
** 返回		: 统计信息指针
********************************************************************/
HEAPMEM_STATISTICS_T *TOOL_HEAPMEM_GetStatistics(void);

/*******************************************************************
** 函数名	: TOOL_HEAPMEM_GetAddress
** 函数描述	: 获取内存池首地址。
** 参数		: 无
** 返回		: 内存池首地址
********************************************************************/
INT8U *TOOL_HEAPMEM_GetAddress(void);

#endif /* TOOL_HEAPMEM_H */
